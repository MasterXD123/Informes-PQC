'use client';

import { useCallback, useState } from 'react';
import { Upload, Image as ImageIcon, Loader2, AlertCircle, FileSpreadsheet } from 'lucide-react';
import { Button } from '@/components/ui/button';
import { Card, CardContent } from '@/components/ui/card';
import { Progress } from '@/components/ui/progress';
import { useReportStore, generateId, ReportItem } from '@/lib/store';
import { useConfigStore } from '@/lib/config-store';
import { useToast } from '@/hooks/use-toast';
import { CSVMapperDialog, ParsedCSVData, CSVColumnMapping } from './CSVMapperDialog';

interface ImageUploaderProps {
  onUploadComplete?: () => void;
}

export function ImageUploader({ onUploadComplete }: ImageUploaderProps) {
  const [isDragging, setIsDragging] = useState(false);
  const [preview, setPreview] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [showCsvDialog, setShowCsvDialog] = useState(false);

  const { setItems, setPeriod, setClient, setIsOcrProcessing, isOcrProcessing } = useReportStore();
  const { getOcrApi } = useConfigStore();
  const { toast } = useToast();

  const processImage = useCallback(async (base64Data: string) => {
    setIsOcrProcessing(true);
    setError(null);

    try {
      const ocrApi = getOcrApi();
      const externalApi = ocrApi ? {
        provider: ocrApi.provider,
        apiKey: ocrApi.apiKey,
        baseUrl: ocrApi.baseUrl,
        model: ocrApi.model,
        ocrSystemPrompt: ocrApi.ocrSystemPrompt,
      } : undefined;

      const response = await fetch('/api/ocr', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ imageBase64: base64Data, externalApi }),
      });

      const result = await response.json();

      if (!response.ok || !result.success) {
        throw new Error(result.error || 'Failed to process image');
      }

      setPeriod(result.data.period || '');
      setItems(result.data.items || []);

      toast({
        title: 'Datos extraídos exitosamente',
        description: `Se encontraron ${result.data.items?.length || 0} registros`,
      });

      onUploadComplete?.();
    } catch (err) {
      const errorMessage = err instanceof Error ? err.message : 'Unknown error';
      setError(errorMessage);
      toast({
        title: 'Error al procesar imagen',
        description: errorMessage,
        variant: 'destructive',
      });
    } finally {
      setIsOcrProcessing(false);
    }
  }, [setItems, setPeriod, setIsOcrProcessing, toast, onUploadComplete, getOcrApi]);

  // Handle CSV import with mapping
  const handleCSVImport = useCallback((data: ParsedCSVData, mapping: CSVColumnMapping[]) => {
    try {
      // Extract field indices from mapping
      const fieldIndices: Record<string, number> = {};
      mapping.forEach((m, idx) => {
        if (m.targetField !== 'ignore') {
          fieldIndices[m.targetField] = idx;
        }
      });

      // Extract metadata (cliente, periodo) from first row
      if (fieldIndices.cliente !== undefined && data.rows[0]) {
        setClient(data.rows[0][fieldIndices.cliente] || '');
      }
      if (fieldIndices.periodo !== undefined && data.rows[0]) {
        setPeriod(data.rows[0][fieldIndices.periodo] || '');
      }

      // Parse items
      const items: ReportItem[] = data.rows.map((row) => {
        const codigo = fieldIndices.codigo !== undefined ? row[fieldIndices.codigo] || '' : '';
        const titulo = fieldIndices.titulo !== undefined ? row[fieldIndices.titulo] || '' : '';
        const fabricacion = fieldIndices.descripcion !== undefined ? row[fieldIndices.descripcion] || '' : '';

        // Mark DESCUENTO items as inactive by default
        const isDescuento = titulo.toUpperCase().includes('DESCUENTO') || 
                           codigo.toUpperCase().includes('DESCUENTO');

        return {
          id: generateId(),
          codigo,
          titulo,
          fabricacion,
          descripcion: '', // Will be generated by AI
          isActive: !isDescuento,
          images: [],
        };
      }).filter(item => item.codigo || item.titulo);

      if (items.length === 0) {
        throw new Error('No se encontraron datos válidos en el CSV');
      }

      setItems(items);

      toast({
        title: 'CSV importado exitosamente',
        description: `Se importaron ${items.length} registros`,
      });

      setShowCsvDialog(false);
      onUploadComplete?.();
    } catch (err) {
      const errorMessage = err instanceof Error ? err.message : 'Unknown error';
      setError(errorMessage);
      toast({
        title: 'Error al importar CSV',
        description: errorMessage,
        variant: 'destructive',
      });
    }
  }, [setItems, setClient, setPeriod, toast, onUploadComplete]);

  const handleDrop = useCallback((e: React.DragEvent) => {
    e.preventDefault();
    setIsDragging(false);

    const file = e.dataTransfer.files[0];
    if (file) {
      if (file.type.startsWith('image/')) {
        const reader = new FileReader();
        reader.onload = (event) => {
          const base64 = event.target?.result as string;
          setPreview(base64);
          processImage(base64);
        };
        reader.readAsDataURL(file);
      } else if (file.name.endsWith('.csv') || file.name.endsWith('.txt')) {
        setShowCsvDialog(true);
      } else {
        setError('Formato no soportado. Use imagen, CSV o TXT.');
      }
    }
  }, [processImage]);

  const handleFileSelect = useCallback((e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (file) {
      if (file.type.startsWith('image/')) {
        const reader = new FileReader();
        reader.onload = (event) => {
          const base64 = event.target?.result as string;
          setPreview(base64);
          processImage(base64);
        };
        reader.readAsDataURL(file);
      } else if (file.name.endsWith('.csv') || file.name.endsWith('.txt')) {
        setShowCsvDialog(true);
      } else {
        setError('Formato no soportado. Use imagen, CSV o TXT.');
      }
    }
  }, [processImage]);

  const handleDragOver = useCallback((e: React.DragEvent) => {
    e.preventDefault();
    setIsDragging(true);
  }, []);

  const handleDragLeave = useCallback((e: React.DragEvent) => {
    e.preventDefault();
    setIsDragging(false);
  }, []);

  const loadSampleData = useCallback(() => {
    const sampleItems: ReportItem[] = [
      {
        id: generateId(),
        codigo: 'P2219-OBRA',
        titulo: 'H2-CAJON DE INGRESO',
        fabricacion: 'Fabricación, ensamblaje y soldadura de cajón de ingreso estructural.',
        descripcion: 'Fabricación y ensamblaje de cajón de ingreso estructural con soldadura certificada.',
        isActive: true,
        images: [],
      },
      {
        id: generateId(),
        codigo: 'P2242-FLUOR',
        titulo: 'TRUSS ESTRUCTURA PRINCIPAL',
        fabricacion: 'Fabricación, soldadura y ensamblaje de truss estructurales.',
        descripcion: 'Montaje de truss estructurales para sistema principal de soporte.',
        isActive: true,
        images: [],
      },
      {
        id: generateId(),
        codigo: 'P2247-CELDAS',
        titulo: 'ESTRUCTURA SOPORTE CELDAS',
        fabricacion: 'Corte, armado y soldadura de estructura soporte para celdas.',
        descripcion: 'Estructura soporte para celdas con corte y soldadura de precisión.',
        isActive: true,
        images: [],
      },
      {
        id: generateId(),
        codigo: 'P2243-CUAJONE',
        titulo: 'DESCUENTO POR EPP',
        fabricacion: 'Descuento aplicado por Equipos de Protección Personal.',
        descripcion: '',
        isActive: false,
        images: [],
      },
    ];

    setPeriod('DEL 9 AL 15/02/2026');
    setClient('Haug S.A.');
    setItems(sampleItems);

    toast({
      title: 'Datos de prueba cargados',
      description: 'Se han cargado datos de ejemplo',
    });

    onUploadComplete?.();
  }, [setItems, setPeriod, setClient, toast, onUploadComplete]);

  return (
    <div className="space-y-4">
      <Card
        className={`glass-card transition-all duration-300 ${
          isDragging
            ? 'border-primary/50 bg-primary/5 scale-[1.02] shadow-lg shadow-primary/20'
            : 'border-white/20 hover:border-primary/30'
        }`}
      >
        <CardContent className="p-0">
          <div
            onDrop={handleDrop}
            onDragOver={handleDragOver}
            onDragLeave={handleDragLeave}
            className="flex flex-col items-center justify-center p-12 text-center cursor-pointer relative overflow-hidden"
          >
            {/* Animated background pattern */}
            <div className="absolute inset-0 opacity-5">
              <div className="absolute inset-0" style={{
                backgroundImage: 'radial-gradient(circle at 1px 1px, currentColor 1px, transparent 0)',
                backgroundSize: '24px 24px'
              }} />
            </div>
            
            {isOcrProcessing ? (
              <div className="space-y-4 relative z-10">
                <div className="relative">
                  <div className="w-16 h-16 rounded-2xl bg-gradient-to-br from-primary to-accent flex items-center justify-center mx-auto shadow-lg glow">
                    <Loader2 className="w-8 h-8 text-white animate-spin" />
                  </div>
                </div>
                <div>
                  <p className="text-lg font-semibold gradient-text">Procesando con IA</p>
                  <p className="text-sm text-muted-foreground mt-1">
                    Extrayendo datos del documento
                  </p>
                </div>
                <Progress className="w-48 h-2" />
              </div>
            ) : preview ? (
              <div className="space-y-4 relative z-10">
                <div className="relative">
                  <img
                    src={preview}
                    alt="Preview"
                    className="max-h-48 rounded-xl shadow-lg ring-2 ring-primary/20"
                  />
                  <div className="absolute inset-0 bg-gradient-to-t from-primary/20 to-transparent rounded-xl" />
                </div>
                <p className="text-sm text-muted-foreground flex items-center gap-2 justify-center">
                  <Loader2 className="w-4 h-4 animate-spin" />
                  Analizando imagen...
                </p>
              </div>
            ) : (
              <>
                <div className="relative z-10">
                  <div className="w-20 h-20 rounded-2xl bg-gradient-to-br from-primary/20 to-accent/20 flex items-center justify-center mb-4 mx-auto border border-white/30 backdrop-blur-sm float">
                    <Upload className="w-10 h-10 text-primary" />
                  </div>
                </div>
                <h3 className="text-lg font-semibold mb-2 relative z-10">
                  Arrastra tu archivo aquí
                </h3>
                <p className="text-sm text-muted-foreground mb-6 relative z-10">
                  Imagen (Excel), CSV o TXT
                </p>
                <div className="flex gap-3 flex-wrap justify-center relative z-10">
                  <label>
                    <input
                      type="file"
                      accept="image/*"
                      onChange={handleFileSelect}
                      className="hidden"
                      disabled={isOcrProcessing}
                    />
                    <Button variant="outline" className="glass-button cursor-pointer hover:scale-105 transition-transform rounded-xl" asChild>
                      <span>
                        <ImageIcon className="w-4 h-4 mr-2" />
                        Imagen
                      </span>
                    </Button>
                  </label>
                  <Button 
                    variant="outline" 
                    onClick={() => setShowCsvDialog(true)}
                    disabled={isOcrProcessing}
                    className="glass-button hover:scale-105 transition-transform rounded-xl"
                  >
                    <FileSpreadsheet className="w-4 h-4 mr-2" />
                    CSV / Pegar
                  </Button>
                </div>
              </>
            )}
          </div>
        </CardContent>
      </Card>

      {error && (
        <div className="flex items-center gap-3 p-4 glass rounded-xl border border-destructive/30 text-destructive animate-in fade-in slide-in-from-top-2 duration-300">
          <div className="w-10 h-10 rounded-xl bg-destructive/10 flex items-center justify-center flex-shrink-0">
            <AlertCircle className="w-5 h-5" />
          </div>
          <div>
            <p className="text-sm font-medium">Error al procesar</p>
            <p className="text-xs text-muted-foreground">{error}</p>
          </div>
        </div>
      )}

      <div className="flex items-center gap-4 py-2">
        <div className="h-px flex-1 bg-gradient-to-r from-transparent via-border to-transparent" />
        <span className="text-xs text-muted-foreground font-medium px-3">O</span>
        <div className="h-px flex-1 bg-gradient-to-r from-transparent via-border to-transparent" />
      </div>

      <Button
        variant="secondary"
        className="w-full glass-button rounded-xl hover:scale-[1.02] transition-all duration-300"
        onClick={loadSampleData}
        disabled={isOcrProcessing}
      >
        <ImageIcon className="w-4 h-4 mr-2" />
        Cargar datos de prueba
      </Button>

      {/* CSV Mapper Dialog */}
      <CSVMapperDialog
        open={showCsvDialog}
        onOpenChange={setShowCsvDialog}
        onImport={handleCSVImport}
      />
    </div>
  );
}
